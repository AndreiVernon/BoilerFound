"""Image validation and local file storage.

Images are identified by their leading bytes, not the filename or the client's Content-Type header
(OWASP ASVS: validate uploads by content). Files are saved under a server-generated name.
"""

import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import Annotated, BinaryIO

from fastapi import Depends

from app.config import Settings, get_settings

_JPEG_MAGIC = b"\xff\xd8\xff"
_PNG_MAGIC = b"\x89PNG\r\n\x1a\n"

CONTENT_TYPES = {".jpg": "image/jpeg", ".png": "image/png"}


class ImageTooLarge(Exception):
    pass


class UnsupportedImageType(Exception):
    pass


@dataclass(frozen=True)
class ValidatedImage:
    data: bytes
    extension: str


def read_and_validate_image(stream: BinaryIO, max_bytes: int) -> ValidatedImage:
    data = stream.read(max_bytes + 1)
    if len(data) > max_bytes:
        raise ImageTooLarge
    if data.startswith(_JPEG_MAGIC):
        return ValidatedImage(data=data, extension=".jpg")
    if data.startswith(_PNG_MAGIC):
        return ValidatedImage(data=data, extension=".png")
    raise UnsupportedImageType


class LocalImageStore:
    def __init__(self, root: Path):
        self.root = root

    def save(self, image: ValidatedImage) -> str:
        self.root.mkdir(parents=True, exist_ok=True)
        key = f"{uuid.uuid4().hex}{image.extension}"
        (self.root / key).write_bytes(image.data)
        return key

    def path_for(self, key: str) -> Path:
        # Keys are generated by save(), but refuse anything that could escape the uploads folder.
        if Path(key).name != key:
            raise ValueError(f"Invalid image key: {key!r}")
        return self.root / key

    def delete(self, key: str) -> None:
        self.path_for(key).unlink(missing_ok=True)


def get_image_store(settings: Annotated[Settings, Depends(get_settings)]) -> LocalImageStore:
    return LocalImageStore(settings.upload_dir)
